"""build repo_radar/static/icons.svg from a local copy of the Lucide icon sources

The interface uses a small, fixed set of Lucide icons (ISC License) served as one SVG sprite,
so the page needs no icon package or network request. To add an icon, append its Lucide name
to ICONS and rerun against any installed `lucide-react` package:

    python scripts/build_icon_sprite.py path/to/node_modules/lucide-react/dist/esm/icons

Only path data is copied. Stroke styling comes from the `.icon` rule in styles.css.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "repo_radar" / "static" / "icons.svg"

ICONS = (
    "arrow-up-right",
    "ban",
    "bookmark",
    "bookmark-check",
    "check",
    "chevron-down",
    "circle-alert",
    "circle-check",
    "circle-dot",
    "clock",
    "code-xml",
    "compass",
    "download",
    "external-link",
    "eye-off",
    "folder-git-2",
    "hard-drive",
    "history",
    "inbox",
    "info",
    "layout-dashboard",
    "library",
    "list-filter",
    "loader-circle",
    "menu",
    "message-square",
    "refresh-cw",
    "rotate-ccw",
    "search",
    "sliders-horizontal",
    "star",
    "trash-2",
    "triangle-alert",
    "users",
    "x",
)

ELEMENT = re.compile(r'\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]')
ATTRIBUTE = re.compile(r'(\w+):\s*"([^"]*)"')
HEADER = (
    "<!-- Lucide icons (https://lucide.dev), ISC License. Copyright (c) Lucide Icons and Contributors.\n"
    "     Portions derived from Feather (MIT, Copyright (c) 2013-present Cole Bemis). See icons-LICENSE.txt.\n"
    "     Generated by scripts/build_icon_sprite.py. -->\n"
)


def icon_symbol(source: Path, name: str) -> str:
    """
    convert one lucide-react icon module into an SVG symbol
    :param source: directory of lucide-react icon modules
    :param name: Lucide icon name
    :returns: SVG symbol markup
    """
    text = (source / f"{name}.mjs").read_text(encoding="utf-8")
    node = text.split("const __iconNode = [", 1)[1].split("];", 1)[0]
    parts = []
    for tag, body in ELEMENT.findall(node):
        attributes = " ".join(f'{key}="{value}"' for key, value in ATTRIBUTE.findall(body) if key != "key")
        parts.append(f"<{tag} {attributes}/>")
    if not parts:
        raise SystemExit(f"No SVG elements were found for the {name} icon")
    return f'  <symbol id="{name}" viewBox="0 0 24 24">{"".join(parts)}</symbol>'


def main(argv: list[str]) -> int:
    """
    write the sprite
    :param argv: command line arguments naming the lucide-react icons directory
    :returns: process exit status
    """
    if len(argv) != 2:
        print(__doc__)
        return 2
    source = Path(argv[1])
    symbols = [icon_symbol(source, name) for name in ICONS]
    OUTPUT.write_text(
        HEADER + '<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols) + "\n</svg>\n", encoding="utf-8"
    )
    print(f"Wrote {len(symbols)} icons to {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
